// Всё, что знает проект о химической формуле, лежит здесь — и только здесь.
//
// Файл читают ДВОЕ:
//   браузер  — <script src="formula.js"> перед solubility_table.js;
//   сервер   — require("../public/formula.js") в server/server.js.
// Поэтому он живёт в public/ (его грузит браузер) и в конце отдаёт себя
// через module.exports, если рядом есть Node.
//
// Зачем один файл на двоих: подпись клетки («MgCl₂»), адрес её страницы
// (mgcl2.html) и заголовок самой страницы обязаны совпадать. Если бы формулу
// собирали в двух местах, они рано или поздно разошлись бы — и ссылка вела бы
// в никуда. Правило проекта то же, что у округления Ar: вычисляемая подпись
// вычисляется, а не хранится.

// В подписи иона встречаются ДВЕ разные цифры, и путать их нельзя:
//   число атомов в группе — внизу: SO₄, NO₂, NH₄, CH₃COO
//   заряд иона            — вверху: ²⁻, ³⁻, ⁺
// Опаснее всего NO₂⁻ и NH₄⁺: если обе цифры набрать одинаково, «NO2-»
// читается как заряд 2−, хотя двойка здесь — два атома кислорода, а заряд
// у нитрит-иона единичный. Поэтому обе цифры берутся из юникода: у ₂ и ² в
// шрифте разная высота по рисунку глифа, а не по сдвигу через CSS, и они не
// сливаются даже вплотную. Разметка <sub>/<sup> тут не годится — при мелком
// кегле оба индекса оказываются на одной высоте.
const SUB = "₀₁₂₃₄₅₆₇₈₉";
const SUP = "⁰¹²³⁴⁵⁶⁷⁸⁹";

// "SO4" -> "SO₄";  цифры внутри формулы группы — это всегда число атомов.
const textSym = (s) => s.replace(/\d/g, (d) => SUB[+d]);

// Заряд: "²⁻", "³⁻", "⁺". Единицу не пишут — Cl⁻, а не Cl¹⁻.
function chargeText(q) {
  const n = Math.abs(q) > 1 ? SUP[Math.abs(q)] : "";
  return n + (q > 0 ? "⁺" : "⁻");
}

// Готовая подпись иона, обычным текстом: SO₄²⁻, NO₂⁻, NH₄⁺, Fe³⁺.
const ionText = (ion) => textSym(ion.sym) + chargeText(ion.charge);

const gcd = (a, b) => (b ? gcd(b, a % b) : a);

// Формула вещества из катиона и аниона, ОБЫЧНЫМИ знаками: "MgCl2",
// "Al2(SO4)3". Индексы — по наименьшему общему кратному зарядов;
// многоатомный ион с индексом больше 1 берётся в скобки.
// Три исключения, где принятая запись отличается от механической:
// H+ + OH- это вода; уксусная кислота пишется CH3COOH, а не HCH3COO;
// H+ + HCO3- механически дало бы "HHCO3" — записи, которой нет ни в одном
// учебнике. Это та же самая угольная кислота H2CO3, что и в клетке H+/CO3 2-:
// H2CO3 ⇌ H+ + HCO3- — первая ступень её диссоциации. Поэтому ЕДИНСТВЕННЫЕ
// две клетки таблицы, которые ведут на одну страницу (/h2co3.html), — эти.
// Кто из них занимает адрес, решает server.js: первая по порядку, карбонатная.
function formulaAscii(cat, an) {
  if (cat.sym === "H" && an.sym === "OH") return "H2O";
  if (cat.sym === "H" && an.sym === "CH3COO") return "CH3COOH";
  if (cat.sym === "H" && an.sym === "HCO3") return "H2CO3";
  const g = gcd(cat.charge, -an.charge);
  const nCat = -an.charge / g;
  const nAn = cat.charge / g;
  const part = (ion, n) =>
    (ion.poly && n > 1 ? "(" + ion.sym + ")" : ion.sym) + (n > 1 ? String(n) : "");
  return part(cat, nCat) + part(an, nAn);
}

// То же самое для показа: "Al2(SO4)3" -> "Al₂(SO₄)₃". Скобки остаются,
// цифры уходят вниз — юникодом, не разметкой (см. комментарий выше).
const formulaText = (ascii) => textSym(ascii);

// Формула вещества из катиона и аниона, сразу в виде для показа.
const formula = (cat, an) => formulaText(formulaAscii(cat, an));

// Адрес страницы вещества: "Al2(SO4)3" -> "al2-so4-3" (+ ".html").
// Всё маленькими буквами; скобка — знак, который в адресе лучше не держать
// (браузеры и мессенджеры его экранируют), поэтому каждая скобка становится
// тире, а сдвоенные и краевые тире убираются: "(NH4)2SO4" -> "nh4-2so4".
// У 345 клеток таблицы 344 разных адреса — это проверено. Совпадение ровно
// одно и оно намеренное: H+/CO3 2- и H+/HCO3- — одна угольная кислота.
const slug = (ascii) =>
  ascii
    .toLowerCase()
    .replace(/[()]/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");

// Разбор формулы на атомы: "Al2(SO4)3" -> { Al: 2, S: 3, O: 12 }.
// Нужен для молярной массы: она складывается из Ar элементов, то есть тоже
// вычисляется, а не хранится. Символ элемента — заглавная буква и, может
// быть, строчная; за ним необязательный индекс; скобочная группа умножается
// на свой индекс целиком.
function atomCounts(ascii) {
  let i = 0;
  const number = () => {
    const m = /^\d+/.exec(ascii.slice(i));
    if (!m) return 1;
    i += m[0].length;
    return +m[0];
  };
  const group = () => {
    const out = {};
    const add = (k, n) => (out[k] = (out[k] || 0) + n);
    while (i < ascii.length && ascii[i] !== ")") {
      if (ascii[i] === "(") {
        i++; // (
        const inner = group();
        i++; // )
        const n = number();
        for (const k in inner) add(k, inner[k] * n);
      } else {
        const m = /^[A-Z][a-z]?/.exec(ascii.slice(i));
        if (!m) throw new Error("не разбирается формула: " + ascii);
        i += m[0].length;
        add(m[0], number());
      }
    }
    return out;
  };
  return group();
}

