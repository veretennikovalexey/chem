// Название вещества.
//
// Правило одно на всю таблицу: анион в именительном падеже плюс катион в
// родительном — «хлорид магния», «гидроксид железа (III)». Так собираются 330
// названий из 345, и ни одно из них не хранится.
//
// Столбец H+ подчиняется тому же правилу: ru2 у водорода — «водорода», и
// правило само даёт «сульфид водорода», «сульфат водорода», «ацетат водорода».
// Но у каждого из этих 15 веществ есть ВТОРОЕ, традиционное имя, которого не
// вычислить ниоткуда: «сероводород», «серная кислота», «уксусная кислота».
// Оно лежит в data/compounds.json, и карточка печатает оба через запятую.
//
// Порядок решает кислород в анионе — то самое школьное деление кислот:
//   бескислородные (F-, Cl-, Br-, I-, S2-) — систематическое имя первым:
//       «Сульфид водорода, сероводород», «Хлорид водорода, хлороводород».
//       Так и должно быть: H2S и HCl — это газы, а «сероводородная» и «соляная
//       кислота» — их растворы в воде, то есть речь уже о другом.
//   кислородсодержащие (SO4 2-, NO3-, CO3 2-, CH3COO- …) — традиционное первым:
//       «Серная кислота, сульфат водорода». «Сульфат водорода» механически
//       верно, но так не пишет ни один учебник; на контрольной нужно первое.
// Кислород ищется в анионе разбором его формулы — тем же atomCounts, что
// считает молярную массу. Признака «бескислородная кислота» в данных нет и не
// нужно: он читается из самой формулы иона и не может с ней разойтись.
//
// Вода — исключение из исключения: правило дало бы «гидроксид водорода», а это
// не название воды. Её систематическое имя, «оксид водорода», карточка и так
// печатает — строкой «Класс».
//
// Названия в compounds.json лежат со строчной буквы: так они пишутся внутри
// предложения. Заглавную ставит cap() — это правило вывода, как округление Ar.
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);

const hasOxygen = (ion) => !!atomCounts(ion.sym).O;

// Единственное место, где имя обязано считать анион ДРУГИМ ионом. Клетка
// H+/HCO3- — не отдельное вещество: это первая ступень диссоциации угольной
// кислоты, H2CO3 ⇌ H+ + HCO3-, и formulaAscii выше уже отдаёт для неё H2CO3.
// Раз формула карбонатная, то и имя карбонатное — иначе подсказка клетки
// сказала бы «гидрокарбонат водорода», а страница, на которую она ведёт,
// «карбонат водорода», и это про одно и то же вещество. Ион подменяется
// целиком и берётся из тех же данных: слово «карбонат» в коде не лежит.
const namedAs = (cat, an, anions) =>
  cat.sym === "H" && an.sym === "HCO3"
    ? (anions || []).find((x) => x.sym === "CO3") || an
    : an;

function compoundName(cat, an, ascii, compounds, anions) {
  an = namedAs(cat, an, anions);
  const systematic = `${an.ru} ${cat.ru2}`;
  const trivial = compounds[ascii];
  if (!trivial) return cap(systematic);
  if (cat.sym === "H" && an.sym === "OH") return cap(trivial);
  return cap(
    hasOxygen(an) ? `${trivial}, ${systematic}` : `${systematic}, ${trivial}`
  );
}

// Node видит module, браузер — нет.
if (typeof module !== "undefined" && module.exports) {
  module.exports = {
    textSym,
    chargeText,
    ionText,
    formulaAscii,
    formulaText,
    formula,
    slug,
    atomCounts,
    cap,
    compoundName,
  };
}
